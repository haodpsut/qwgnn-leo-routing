#!/usr/bin/env python3
"""Sinh macro + bảng cho R7.1 (độ bền với trạng thái mạng không hoàn hảo).

⛔ Mọi con số của mục mới PHẢI sinh từ đây, không gõ tay vào .tex. Bài này đã có một lần
bảng gõ tay không cập nhật theo lần chạy lại; `check_artifact_claims.py` của kho tồn tại
vì chuyện đó.

    python3 experiments/emit_r7_macros.py
    python3 experiments/emit_r7_macros.py --tu-kiem
"""
import argparse
import csv
import io
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CSV = os.path.join(ROOT, "results", "r7_1_imperfect_state.csv")
OUT_M = os.path.join(ROOT, "results", "r7_macros.tex")
OUT_T = os.path.join(ROOT, "results", "tab-imperfect.tex")

# (ten truc trong CSV, tien to macro, nhan in ra bang)
TRUC = [
    ("demand-estimation errors",       "Dem",   r"demand-estimation errors ($\sigma$)"),
    ("stale telemetry",                "Stale", r"stale telemetry (slots, $60$\,s each)"),
    ("ephemeris or capacity mismatch", "Eph",   r"ephemeris error ($\sigma$)"),
    ("link failures",                  "Fail",  r"link failures (fraction of ISLs)"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tu-kiem", action="store_true")
    if ap.parse_args().tu_kiem:
        return tu_kiem()
    if not os.path.exists(CSV):
        sys.exit("⛔ chua co %s" % os.path.relpath(CSV, ROOT))
    r = list(csv.DictReader(io.open(CSV, encoding="utf-8")))
    f = float

    don_vi = sorted({(x["shell"], x["seed"]) for x in r})
    L = [r"% Auto-generated by experiments/emit_r7_macros.py -- KHONG sua tay",
         r"\newcommand{\rImpUnits}{%d}" % len(don_vi),
         r"\newcommand{\rImpShells}{%d}" % len({x["shell"] for x in r}),
         r"\newcommand{\rImpSeeds}{%d}" % len({x["seed"] for x in r})]

    sach_h = st.median(f(x["rec_hoc_sach"]) for x in r)
    sach_u = st.median(f(x["rec_mu_sach"]) for x in r)
    L += [r"\newcommand{\rImpCleanLearned}{%.3f}" % sach_h,
          r"\newcommand{\rImpCleanBlind}{%.3f}" % sach_u]

    hang = []
    for ten, tt, nhan in TRUC:
        mucs = sorted({x["muc"] for x in r if x["truc"] == ten}, key=float)
        o = []
        for m in mucs:
            sel = [x for x in r if x["truc"] == ten and x["muc"] == m]
            dh = st.median(f(x["rec_hoc"]) - f(x["rec_hoc_sach"]) for x in sel)
            du = st.median(f(x["rec_mu"]) - f(x["rec_mu_sach"]) for x in sel)
            o.append((m, dh, du))
        hang.append((nhan, o))
        # macro cho muc NANG NHAT, la con so di vao van xuoi
        m, dh, du = o[-1]
        L += [r"\newcommand{\rImp%sWorst}{%s}" % (tt, m),
              r"\newcommand{\rImp%sDL}{%+.3f}" % (tt, dh),
              r"\newcommand{\rImp%sDB}{%+.3f}" % (tt, du)]

    # ty le: telemetry cu hai chinh sach lech bao nhieu lan
    _, dh_s, du_s = hang[1][1][-1]
    if abs(du_s) > 1e-9:
        L.append(r"\newcommand{\rImpStaleRatio}{%.0f}" % (abs(dh_s) / abs(du_s)))
    _, dh_f, du_f = hang[3][1][-1]
    if abs(dh_f) > 1e-9:
        L.append(r"\newcommand{\rImpFailRatio}{%.1f}" % (abs(du_f) / abs(dh_f)))

    # ⛔ CONG: moc mu PHAI bang 0 tuyet doi tren truc nhu cau. Neu khong thi bo do sai.
    dem = [x for x in r if x["truc"] == "demand-estimation errors"]
    lech = max(abs(f(x["rec_mu"]) - f(x["rec_mu_sach"])) for x in dem)
    if lech > 1e-9:
        sys.exit("⛔ moc mu DOI %.3g tren truc nhu cau, trong khi no khong doc nhu cau. "
                 "Bo do sai, dung sinh macro." % lech)
    L.append(r"\newcommand{\rImpBlindDemandExact}{%s}" % ("0" if lech == 0 else "%.1g" % lech))

    io.open(OUT_M, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("ghi %s (%d macro)" % (os.path.relpath(OUT_M, ROOT), len(L) - 1))

    # ---- bang mot cot ----
    T = [r"% SINH TU repo/experiments/emit_r7_macros.py -- DUNG SUA TAY.",
     r"\begin{table}[t]", r"\centering", r"\footnotesize",
         r"\caption{Sensitivity to imperfect network state information, the four degradations"
         r" named by Reviewer~1. Entries are the change in recovered fraction from the clean"
         r" case (learned $\rImpCleanLearned$, blind multipath $\rImpCleanBlind$), median over"
         r" $\rImpUnits$ (shell, seed) units, $\rImpShells$ shells $\times$ $\rImpSeeds$ seeds."
         r" Each policy routes on the state the operator \emph{believes}; travel time is"
         r" measured on the state that actually holds. Negative is worse.}",
         r"\label{tab:imperfect}",
         r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
         r"degradation & level & learned & blind \\", r"\midrule"]
    for nhan, o in hang:
        T.append(r"\multicolumn{4}{@{}l@{}}{\emph{%s}}\\" % nhan)
        for m, dh, du in o:
            T.append(r"& %s & $%+.3f$ & $%+.3f$ \\" % (m, dh, du))
    T += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    io.open(OUT_T, "w", encoding="utf-8").write("\n".join(T))
    print("ghi %s (%d dong)" % (os.path.relpath(OUT_T, ROOT), len(hang)))
    for x in L[1:]:
        print("   " + x)
    return 0


def tu_kiem():
    """Đối chứng: cổng phải chặn khi mốc mù đổi trên trục nhu cầu."""
    import tempfile
    import subprocess
    print("== TU KIEM emit_r7_macros ==\n")
    d = tempfile.mkdtemp()
    os.makedirs(os.path.join(d, "results"))
    cot = ["shell", "seed", "truc", "muc", "rec_hoc_sach", "rec_mu_sach", "rec_hoc", "rec_mu"]

    def ghi(mu_nhieu):
        rows = []
        for ten in [t[0] for t in TRUC]:
            for m in ("0.1", "0.4"):
                rows.append(dict(shell="w1", seed="0", truc=ten, muc=m,
                                 rec_hoc_sach="0.900", rec_mu_sach="0.700",
                                 rec_hoc="0.880",
                                 rec_mu=mu_nhieu if ten == "demand-estimation errors"
                                 else "0.690"))
        with io.open(os.path.join(d, "results", "r7_1_imperfect_state.csv"), "w",
                     newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=cot)
            w.writeheader(); w.writerows(rows)

    def chay():
        import shutil
        me = os.path.join(d, "experiments")
        os.makedirs(me, exist_ok=True)
        shutil.copy(os.path.abspath(__file__), me)
        return subprocess.run([sys.executable, os.path.join(me, os.path.basename(__file__))],
                              capture_output=True, text=True)

    ghi("0.700")                    # moc mu KHONG doi -> phai sinh duoc
    r1 = chay()
    d1 = r1.returncode == 0
    print("  %-52s %s" % ("moc mu khong doi tren truc nhu cau: phai SINH", "DAT" if d1 else "HONG"))

    ghi("0.690")                    # moc mu DOI -> phai CHAN
    r2 = chay()
    d2 = r2.returncode != 0 and "khong doc nhu cau" in (r2.stdout + r2.stderr)
    print("  %-52s %s" % ("moc mu DOI tren truc nhu cau: phai CHAN", "DAT" if d2 else "HONG"))

    ok = d1 and d2
    print("\n  => %s" % ("TAT CA DAT" if ok else "CO CA HONG"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
